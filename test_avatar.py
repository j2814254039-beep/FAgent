"""临时测试：让窗口显示一张图片。

跑法：
    .venv\\Scripts\\python.exe test_avatar.py

看到窗口里有一块蓝色背景 + 一根白色竖条，就成功了。
"""

import tkinter as tk
from pathlib import Path

# ---------------------------------------------------------------
# 1. 找到图片
#    __file__ = 这个脚本自己的路径
#    .parent  = 它所在的目录（项目根 D:\MyAiAgent）
# ---------------------------------------------------------------
IMAGE = Path(__file__).parent / "assets" / "avatar" / "walk" / "01.png"

print("图片路径：", IMAGE)
print("文件存在吗：", IMAGE.exists())

# ---------------------------------------------------------------
# 2. 创建窗口
#    tk.Tk() 相当于 Java 的 new JFrame()
# ---------------------------------------------------------------
root = tk.Tk()
root.title("虚拟形象测试")
root.geometry("320x320")

# ---------------------------------------------------------------
# 3. 读图片
#    tkinter 原生只认 PNG / GIF，不认 JPG
#    ★ 必须赋值给变量 photo —— 不存的话对象会被垃圾回收，窗口就是空白
# ---------------------------------------------------------------
photo = tk.PhotoImage(file=str(IMAGE))

# ---------------------------------------------------------------
# 4. 把图片放进一个标签，再把标签塞进窗口
#    Label 相当于 Java 的 JLabel
# ---------------------------------------------------------------
label = tk.Label(root, image=photo)
label.pack()

# ---------------------------------------------------------------
# 5. 进入事件循环
#    ★ 这行会【阻塞】，直到窗口被关闭 —— 后面的代码暂时不会执行
# ---------------------------------------------------------------
root.mainloop()

print("窗口已关闭")
